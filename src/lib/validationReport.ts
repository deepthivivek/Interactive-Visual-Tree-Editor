/**
 * Pure Validation Report Generation Module (Day 13).
 *
 * Transforms a raw validation result into a clean, sanitized, and exportable
 * validation report document (version 1 schema).
 *
 * Principles:
 * - Independent Schema: Preserves the core graph schema ({"version":1,"nodes":[],"edges":[]}).
 * - Sanitized: Excludes transient UI state, viewport coordinates, and private attributes.
 * - Pure: Never mutates the source validation result or graph data.
 */

import type {
  ValidationResult,
  ValidationIssue,
  ValidationSeverity,
  ValidationIssueType,
  ValidationConfidence,
  GraphQualityMetrics,
  ValidationCoverageReport,
} from './validation';
import type { ValidationComparison } from './validationComparison';

export interface ValidationReportIssueItem {
  id: string;
  severity: ValidationSeverity;
  type: ValidationIssueType;
  message: string;
  affectedNodes: string[];
  affectedEdges: string[];
  field?: string;
  evidence: Record<string, unknown>;
  suggestedFix?: string;
  rootCauseGroupId?: string;
  confidence: ValidationConfidence;
}

export interface ValidationReportDocument {
  reportVersion: 1;
  status: 'VALID' | 'INVALID';
  valid: boolean;
  score: number;
  summary: {
    criticalCount: number;
    errorCount: number;
    warningCount: number;
    totalIssues: number;
    affectedNodeCount: number;
  };
  metrics: GraphQualityMetrics;
  coverage: ValidationCoverageReport;
  issues: ValidationReportIssueItem[];
  comparisonSummary?: {
    hasRegressed: boolean;
    hasImproved: boolean;
    newIssueCount: number;
    resolvedIssueCount: number;
    scoreDelta: number;
    summary: string;
  };
  disclaimer: string;
}

export interface GenerateReportOptions {
  comparison?: ValidationComparison;
}

const COMPLIANCE_DISCLAIMER =
  'This report is generated by a demonstration compliance policy editor. Validation passes indicate adherence to internal graph grammar rules and do not constitute legal compliance, official regulatory adherence, or production certification.';

/**
 * Generates a clean, serializable Validation Report Document.
 * Pure and non-mutating.
 */
export function generateValidationReport(
  validationResult: ValidationResult,
  options?: GenerateReportOptions
): ValidationReportDocument {
  const criticalCount = validationResult.issues.filter((i) => i.severity === 'CRITICAL').length;
  const errorCount = validationResult.issues.filter((i) => i.severity === 'ERROR').length;
  const warningCount = validationResult.issues.filter((i) => i.severity === 'WARNING').length;

  const sanitizedIssues: ValidationReportIssueItem[] = validationResult.issues.map((issue) => ({
    id: issue.id,
    severity: issue.severity,
    type: issue.type,
    message: issue.message,
    affectedNodes: [...issue.nodeIds],
    affectedEdges: [...issue.edgeIds],
    field: issue.field,
    evidence: { ...issue.evidence },
    suggestedFix: issue.suggestedFix,
    rootCauseGroupId: issue.rootCauseGroupId,
    confidence: issue.confidence,
  }));

  const report: ValidationReportDocument = {
    reportVersion: 1,
    status: validationResult.valid ? 'VALID' : 'INVALID',
    valid: validationResult.valid,
    score: validationResult.score,
    summary: {
      criticalCount,
      errorCount,
      warningCount,
      totalIssues: validationResult.issues.length,
      affectedNodeCount: validationResult.affectedNodeIds.length,
    },
    metrics: { ...validationResult.metrics },
    coverage: JSON.parse(JSON.stringify(validationResult.coverage)),
    issues: sanitizedIssues,
    disclaimer: COMPLIANCE_DISCLAIMER,
  };

  if (options?.comparison) {
    report.comparisonSummary = {
      hasRegressed: options.comparison.hasRegressed,
      hasImproved: options.comparison.hasImproved,
      newIssueCount: options.comparison.newIssues.length,
      resolvedIssueCount: options.comparison.resolvedIssues.length,
      scoreDelta: options.comparison.scoreDelta,
      summary: options.comparison.summary,
    };
  }

  return report;
}
